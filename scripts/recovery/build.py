"""Deterministic local build of a standalone payload and exact inspection command; no network."""
import hashlib
from pathlib import Path
import shlex

ROOT=Path(__file__).resolve().parents[2]

def artifacts():
    source=(ROOT/'scripts/recovery/backup.py').read_text()
    generator=(ROOT/'docs/pilot/baseline-select-plan.py.txt').read_text()
    policy=(ROOT/'docs/pilot/baseline-contract.json').read_text()
    source=source.replace("BASE = Path(__file__).resolve().parents[2]", "BASE = Path('/')")
    source=source.replace("path=BASE/'docs/pilot/baseline-select-plan.py.txt';raw=path.read_bytes()", "path='<embedded-generator>';raw=GENERATOR_TEXT.encode()")
    source=source.replace("json.loads((BASE/'docs/pilot/baseline-contract.json').read_text())", "json.loads(POLICY_TEXT)")
    payload=('# Generated by scripts/recovery/build.py; inspect source/tests before approval.\nGENERATOR_TEXT = '+repr(generator)+'\nPOLICY_TEXT = '+repr(policy)+'\n'+source).encode()
    digest=hashlib.sha256(payload).hexdigest()
    bootstrap="import os,hashlib; p=os.environ.pop('CSF_REVIEWED_PAYLOAD'); h=hashlib.sha256(p.encode()).hexdigest(); assert h=='"+digest+"','payload digest mismatch'; exec(compile(p,'<reviewed-memory-payload>','exec'),{'__name__':'__main__','__file__':'<reviewed-memory-payload>','PAYLOAD_DIGEST':h})"
    # Binding JSON remains stdin; public code env is removed before any DB client starts.
    commands={}
    for mode,limit,grace in (('inspect',115,5),('capture',1770,30)):
        commands['scripts/recovery/'+mode+'.command.sh']=("set -euo pipefail\nset +x\numask 077\nexport PATH=/usr/bin:/bin\nexec /usr/bin/timeout --signal=TERM --kill-after="+str(grace)+"s "+str(limit)+"s /usr/bin/python3 -I -B -c "+shlex.quote(bootstrap)+" "+mode+"\n").encode()
    return {'scripts/recovery/payload.py':payload,**commands}

if __name__=='__main__':
    for name,data in artifacts().items():(ROOT/name).write_bytes(data)
    names=sorted([*artifacts(),'scripts/recovery/backup.py','scripts/recovery/build.py','scripts/recovery/run.sh','docs/pilot/baseline-contract.json','docs/pilot/baseline-select-plan.py.txt'])
    (ROOT/'scripts/recovery/PAYLOAD.sha256').write_text(''.join(hashlib.sha256((ROOT/n).read_bytes()).hexdigest()+'  '+n+'\n' for n in names))
